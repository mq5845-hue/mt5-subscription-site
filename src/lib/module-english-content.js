function bullets(items) {
  return items.map((item) => `- ${item}`).join('\n');
}

export function getEnglishModuleContent(entry) {
  const profile = profiles[entry.slug];
  if (!profile) return '';

  const title = entry.title.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2');
  return [
    `# ${title}`,
    '',
    '## Purpose',
    profile.purpose,
    '',
    '## Core responsibilities',
    bullets(profile.responsibilities),
    '',
    '## Inputs and dependencies',
    bullets(profile.inputs),
    '',
    '## Outputs and contracts',
    bullets(profile.outputs),
    '',
    '## Implementation workflow',
    '1. Load and validate configuration before processing market or account events.',
    '2. Normalize inputs into explicit, testable values and reject incomplete state.',
    '3. Execute the module responsibility without bypassing risk or ownership boundaries.',
    '4. Return a deterministic result with reason codes and structured evidence.',
    '5. Persist only the state required for safe restart and recovery.',
    '',
    '## Validation checklist',
    bullets(profile.validation),
    '- Confirm deterministic behavior in both Strategy Tester and live-event sequences.',
    '- Confirm all failure paths default to a safe state and produce actionable logs.',
    '- Compile the integrated MQL5 product with zero errors and zero warnings.',
    '',
    '## Integration notes',
    'Keep this module behind a narrow interface. Strategy rules may request an action, but configuration, risk, execution, logging, and recovery controls retain their own authority. Version every public contract and include the module in regression, stress, and restart testing before release.',
  ].join('\n');
}
